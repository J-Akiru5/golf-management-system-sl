/**
 * Builds the SQL seed for the 24th Bamboo Tee field from the club's own sheet.
 *
 * The sheet is kept as data (supabase/seed/*.psv); this script turns it into one reviewable SQL
 * block. It never fills a gap the club left: a blank index stays blank, a partner whose schedule
 * differs keeps their own days and both registrations are marked needs_review.
 *
 *   pnpm exec tsx scripts/seed-bamboo-tee-field.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  MAX_READABLE_INDEX,
  parseFieldSheet,
  parseWaitingList,
  summariseField,
  fieldIssues,
  type FieldPlayer,
  type FieldPair,
} from "../src/lib/seed/bamboo-tee-field";

const SEED = join(process.cwd(), "supabase", "seed");
const OUT = join(SEED, "bamboo-tee-2026-field.sql");

const field = parseFieldSheet(readFileSync(join(SEED, "bamboo-tee-2026-field.psv"), "utf8"));
const waiting = parseWaitingList(
  readFileSync(join(SEED, "bamboo-tee-2026-waiting-list.psv"), "utf8"),
);

/** The club writes `LOPINGCO,JOSHUA` and `TAN , JUAN RICARDO`; one spelling goes into the database. */
function tidyName(name: string): string {
  return name
    .replace(/\s*,\s*/g, ", ")
    .replace(/\s+/g, " ")
    .replace(/,$/, "")
    .trim();
}

const sameSchedule = (a: FieldPlayer, b: FieldPlayer) =>
  JSON.stringify(a.schedule) === JSON.stringify(b.schedule);

function notesFor(pair: FieldPair, side: "member" | "guest"): string[] {
  const player = pair[side];
  const partner = side === "member" ? pair.guest : pair.member;
  const notes: string[] = [];
  if (!/^\S[^,]*,\s*\S/.test(player.name)) {
    notes.push("The name on the club sheet is incomplete.");
  }
  if (player.schedule.length === 0) {
    notes.push("No schedule on the club sheet.");
  } else {
    if (player.schedule.length === 1) notes.push("The club sheet gives one playing day.");
    if (player.scheduleNote) {
      notes.push(`The schedule on the club sheet is incomplete: ${player.scheduleNote}`);
    }
    if (partner.schedule.length > 0 && !sameSchedule(player, partner)) {
      notes.push("The partner is on a different schedule on the club sheet.");
    }
  }
  // A blank index is not a reason to hold the player back: the event rule treats an unverified
  // handicap as 0 when it routes. A number that cannot be an index is, so it is not recorded.
  if (player.index !== null && player.index > MAX_READABLE_INDEX) {
    notes.push(
      `The club sheet shows ${player.index}, which is not a handicap index, so no index was recorded.`,
    );
  }
  return notes;
}

const q = (value: string) => `'${value.replace(/'/g, "''")}'`;

function playerRow(pair: FieldPair, side: "member" | "guest"): string {
  const player = pair[side];
  const name = tidyName(player.name);
  const index =
    player.index === null || player.index > MAX_READABLE_INDEX ? "null" : player.index.toFixed(1);
  const [first, second] = player.schedule;
  const note = notesFor(pair, side).join(" ");
  return [
    `(${pair.number}`,
    q(name),
    q(side),
    index,
    first ? String(first.day) : "null",
    first ? q(first.session) : "null",
    second ? String(second.day) : "null",
    second ? q(second.session) : "null",
    `${q(note)})`,
  ].join(", ");
}

const fieldRows = field.flatMap((pair) => [
  playerRow(pair, "member"),
  playerRow(pair, "guest"),
]);
// The waiting list has no index and no partner, so it creates directory entries only.
const waitingValues = waiting
  .map((entry) => `      (${entry.number}, ${q(tidyName(entry.name))})`)
  .join(",\n");

const sql = `-- 24th Bamboo Tee: the club's own field, from the sheet supplied on 4 November 2026.
--
-- Generated by scripts/seed-bamboo-tee-field.ts from
--   supabase/seed/bamboo-tee-2026-field.psv        (${field.length} member and guest pairs)
--   supabase/seed/bamboo-tee-2026-waiting-list.psv (${waiting.length} players with no partner)
--
-- Review it, then run it in the Supabase SQL editor on the project that holds the event. It is not
-- a migration: it is data, and the event it finds by name decides where it lands. It needs
-- migration 20261105000100 (registration_days.session), which the desk's AM/PM choice depends on.
--
-- What it writes
--   * one player per name on the sheet, matched by name inside the club
--   * a member or guest membership when the player has none
--   * the index on the sheet as of the event's cut-off date, source ngap_import
--   * one registration per player with the index frozen at the cut-off
--   * the player's own playing days and AM/PM session from the sheet
--
-- What it does not write, on purpose
--   * an index the sheet leaves blank, and the 203 on pair 104. A blank is not zero, and the event
--     rule treats an unverified handicap as 0 when it routes, so nothing is invented here; 203 is
--     not an index, so the player is registered without one and marked needs_review
--   * one partner's schedule for the other. When the two differ, each player keeps their own days
--     and both registrations are marked needs_review with the reason
--   * days for a player whose sheet count does not match the event's required days. The
--     registration is marked needs_review instead of writing days the day rule would refuse
--   * a team, a class, a flight or a tee time. The desk makes those after the field is confirmed
--
-- Re-running it is safe: players are matched by name, the index and the registration are updated in
-- place, and days are merged rather than replaced.

begin;

do $$
declare
  v_event_name constant text := 'Bamboo';
  v_club uuid;
  v_tournament uuid;
  v_cutoff date;
  v_required_days smallint;
  v_player uuid;
  v_reg uuid;
  v_note text;
  v_reasons text[];
  v_day_count integer;
  v_write_days boolean;
  r record;
  w record;
begin
  select t.id, t.club_id, t.cutoff_date, t.required_days
    into v_tournament, v_club, v_cutoff, v_required_days
    from public.tournaments t
   where t.name ilike '%' || v_event_name || '%'
   order by t.play_date desc
   limit 1;

  if v_tournament is null then
    raise exception 'No event matching "%" was found. Set v_event_name and run this again.', v_event_name;
  end if;

  -- The field: one row per player, with the days and sessions the club wrote for that player.
  for r in
    select * from (values
${fieldRows.map((row) => `      ${row}`).join(",\n")}
    ) as f(pair_no, full_name, role, idx, d1, s1, d2, s2, note)
  loop
    v_note := btrim(r.note);
    v_day_count := (case when r.d1 is null then 0 else 1 end) + (case when r.d2 is null then 0 else 1 end);
    v_write_days := v_day_count > 0;

    if v_write_days and v_required_days is not null and v_day_count <> v_required_days then
      v_note := concat_ws(' ', nullif(v_note, ''),
        format('The club sheet gives %s playing day(s); this event requires %s, so the days were left for the desk.',
               v_day_count, v_required_days));
      v_write_days := false;
    end if;

    select p.id into v_player
      from public.players p
     where p.club_id = v_club
       and lower(btrim(p.full_name)) = lower(r.full_name)
     limit 1;

    if v_player is null then
      insert into public.players (club_id, full_name)
      values (v_club, r.full_name)
      returning id into v_player;
    end if;

    if not exists (
      select 1 from public.player_memberships m
       where m.club_id = v_club and m.player_id = v_player and m.status = 'active'
    ) then
      insert into public.player_memberships (club_id, player_id, membership_type)
      values (v_club, v_player, r.role);
    end if;

    if r.idx is not null then
      insert into public.handicap_records (club_id, player_id, handicap_index, effective_date, source)
      values (v_club, v_player, r.idx, v_cutoff, 'ngap_import')
      on conflict (player_id, effective_date)
      do update set handicap_index = excluded.handicap_index, source = excluded.source;
    end if;

    v_reasons := case when v_note = '' then '{}'::text[] else array[v_note] end;

    insert into public.registrations (club_id, tournament_id, player_id, frozen_index, status, reasons)
    values (v_club, v_tournament, v_player, r.idx,
            case when v_note = '' then 'ok' else 'needs_review' end, v_reasons)
    on conflict (tournament_id, player_id)
    do update set frozen_index = excluded.frozen_index,
                  status = excluded.status,
                  reasons = excluded.reasons
    returning id into v_reg;

    if v_write_days then
      insert into public.registration_days (club_id, registration_id, tournament_day_id, selected, session)
      select v_club, v_reg, d.id, true, s.session
        from (values (r.d1, r.s1), (r.d2, r.s2)) as s(day_no, session)
        join public.tournament_days d
          on d.tournament_id = v_tournament
         and d.club_id = v_club
         and d.day_number = s.day_no
         and d.is_playing_day
       where s.day_no is not null
      on conflict (registration_id, tournament_day_id)
      do update set selected = true, session = excluded.session, updated_at = now();
    end if;

    -- A day the club no longer gives this player is released, keeping the row for the desk.
    update public.registration_days rd
       set selected = false,
           session = null,
           tee_time = null,
           start_hole = null,
           tee_confirmed = false,
           updated_at = now()
     where rd.registration_id = v_reg
       and rd.selected
       and not exists (
         select 1 from public.tournament_days d
          where d.id = rd.tournament_day_id
            and d.day_number in (coalesce(r.d1, -1), coalesce(r.d2, -1))
       );
  end loop;

  -- Players on the sheet with no guest partner yet. Directory entries only: no index, no
  -- registration, nothing guessed about the days they will play.
  for w in
    select * from (values
${waitingValues}
    ) as f(pair_no, full_name)
  loop
    if not exists (
      select 1 from public.players p
       where p.club_id = v_club and lower(btrim(p.full_name)) = lower(w.full_name)
    ) then
      insert into public.players (club_id, full_name)
      values (v_club, w.full_name);
    end if;
  end loop;
end $$;

commit;
`;

writeFileSync(OUT, sql, "utf8");

const review = field.flatMap((p) => notesFor(p, "member").concat(notesFor(p, "guest")));
const summary = summariseField(field, fieldIssues(field));
console.log(
  [
    `wrote ${OUT}`,
    `${field.length} pairs, ${field.length * 2} players, ${waiting.length} waiting-list players`,
    `${review.filter((note) => note.length > 0).length} player rows carry a needs_review reason`,
    `mismatched schedules: ${summary.mismatched}`,
    `blank indexes: ${summary.missingIndex}`,
    `unreadable indexes: ${summary.unreadableIndex}`,
    `no schedule: ${summary.noSchedule}`,
    `incomplete schedule: ${summary.incomplete}`,
    `single day: ${summary.singleDay}`,
    `pairs whose partners agree: ${summary.pairs - summary.mismatched}`,
  ].join("\n"),
);
